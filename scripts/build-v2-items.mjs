const VERSION = 'v2-bank-pilot';
const items = [];

function addBlock({
  prefix,
  domain,
  variable,
  scoreGroup,
  responseScale = 'agreement',
  rows,
}) {
  rows.forEach(([facet, scoringKey, text, sourceItemId = null], index) => {
    items.push({
      item_id: `${prefix}${String(index + 1).padStart(2, '0')}`,
      text,
      is_imc: scoringKey === 'imc',
      expected: scoringKey === 'imc' ? Number(sourceItemId) : null,
      domain,
      variable,
      facet,
      scoring_key: scoringKey,
      response_scale: responseScale,
      score_group: scoreGroup,
      version: VERSION,
      source_item_id: scoringKey === 'imc' ? null : sourceItemId,
    });
  });
}

